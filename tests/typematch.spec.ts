import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('search, recommendations, keyboard controls, preview modes and clipboard', async ({ page, context }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Better type. Together.' })).toBeVisible()
  await expect(page.getByRole('radio')).toHaveCount(3)
  await page.getByRole('radio', { name: 'DM Sans', exact: true }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('radio', { name: 'Source Sans 3', exact: true })).toBeChecked()
  await expect(page.locator('.website-specimen')).toHaveCSS('font-family', /Source Sans 3/)
  await page.getByRole('button', { name: 'Heading font: Playfair Display' }).click()
  await page.getByRole('combobox').fill('mont')
  await page.getByRole('combobox').press('Enter')
  await expect(page.getByRole('button', { name: 'Heading font: Montserrat' })).toBeFocused()
  await expect(page.getByRole('radio', { name: 'Source Serif 4', exact: true })).toBeChecked()
  await expect(page.locator('.specimen-title')).toHaveCSS('font-family', /Montserrat/)
  await page.getByRole('button', { name: 'Mobile preview', exact: true }).click()
  await expect(page.getByTestId('specimen')).toHaveAttribute('data-mode', 'mobile')
  expect((await page.getByTestId('specimen').boundingBox())?.width).toBe(322)
  await page.getByRole('button', { name: 'Desktop preview', exact: true }).click()
  await expect(page.getByTestId('specimen')).toHaveAttribute('data-mode', 'desktop')
  await page.getByRole('button', { name: 'Copy CSS', exact: true }).click()
  const css = await page.evaluate(() => navigator.clipboard.readText())
  expect(css).toContain('Montserrat:wght@600')
  expect(css).toContain("font-family: 'Source Serif 4', serif")
  expect(css.startsWith('@import')).toBe(true)
  await page.getByRole('button', { name: 'Google Fonts import' }).click()
  await page.getByRole('button', { name: 'Copy import', exact: true }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toMatch(/^@import url\('https:\/\/fonts.googleapis.com\/css2\?.*'\);$/)
  expect(errors).toEqual([])
})

test('empty search, Escape, outside click and visible keyboard focus', async ({ page }) => {
  await page.goto('/')
  const trigger = page.getByRole('button', { name: /Heading font:/ })
  await trigger.focus()
  await page.keyboard.press('Enter')
  await page.getByRole('combobox').fill('zzyx')
  await page.keyboard.press('Enter')
  await expect(page.getByText('No fonts found for “zzyx”')).toBeVisible()
  await page.getByRole('button', { name: 'Clear search', exact: true }).last().click()
  await expect(page.getByRole('option')).toHaveCount(28)
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await expect(trigger).toHaveCSS('outline-style', 'solid')
  await trigger.click()
  await page.getByRole('heading', { level: 1 }).click()
  await expect(page.getByRole('listbox')).toHaveCount(0)
})

test('desktop and mobile visual evidence, assets and accessible semantics', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => document.fonts.ready)
  await expect(page.locator('.font-load-status')).toContainText('preview ready', { timeout: 20000 })
  expect(await page.evaluate(() => document.fonts.check('600 66px "Playfair Display"'))).toBe(true)
  expect(await page.evaluate(() => document.fonts.check('400 14px "DM Sans"'))).toBe(true)
  const images = await page.locator('img').evaluateAll(nodes => nodes.map(node => {
    const img = node as HTMLImageElement
    return { loaded: img.complete && img.naturalWidth > 0, width: img.width, intrinsic: img.naturalWidth }
  }))
  expect(images.every(img => img.loaded && img.width === img.intrinsic)).toBe(true)
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true })
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  await page.getByRole('button', { name: /Heading font:/ }).click()
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload()
  await page.evaluate(() => document.fonts.ready)
  await expect(page.getByRole('button', { name: 'Mobile preview', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true })
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.getByRole('button', { name: 'Desktop preview', exact: true }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
})

test('blocked font service and clipboard failures stay usable', async ({ page }) => {
  await page.route('https://fonts.googleapis.com/**', route => route.abort())
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'clipboard', { value: { writeText: () => Promise.reject(new Error('Denied')) }, configurable: true })
  })
  await page.goto('/')
  await expect(page.getByText('Fonts couldn’t load. Showing system fallbacks.')).toBeVisible()
  await page.getByRole('button', { name: 'Copy CSS', exact: true }).click()
  await expect(page.getByRole('textbox')).toBeFocused()
  await expect(page.getByRole('textbox')).toContainText('@import')
  await expect(page.getByText('CSS copied to clipboard')).toHaveCount(0)
  await page.unroute('https://fonts.googleapis.com/**')
  await page.getByRole('button', { name: 'Retry fonts' }).click()
  await expect(page.locator('.font-load-status')).toContainText('preview ready', { timeout: 20000 })
})
