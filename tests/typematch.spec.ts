test('desktop and mobile visual evidence, assets and accessible semantics', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => document.fonts.ready)
  await expect(page.locator('.font-load-status')).toContainText('preview ready', { timeout: 20000 })
  expect(await page.evaluate(() => document.fonts.check('600 66px "Playfair Display"'))).toBe(true)
  expect(await page.evaluate(() => document.fonts.check('400 14px "DM Sans"'))).toBe(true)
  const images = await page.locator('img').evaluateAll(nodes => nodes.map(node => {
    const img = node as HTMLImageElement
    return { loaded: img.complete && img.naturalWidth > 0, width: img.width, intrinsic: img.naturalWidth }
  }))
  expect(images.every(img => img.loaded && img.width === img.intrinsic)).toBe(true)
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true })
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  await page.getByRole('button', { name: /Heading font:/ }).click()
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload()
  await page.evaluate(() => document.fonts.ready)
  await expect(page.locator('.font-load-status')).toContainText('preview ready', { timeout: 20000 })
  await expect(page.getByRole('button', { name: 'Mobile preview', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true })
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.getByRole('button', { name: 'Desktop preview', exact: true }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
})

test('blocked font service and clipboard failures stay usable', async ({ page }) => {
  await page.route('https://fonts.googleapis.com/**', route => route.abort())
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'clipboard', { value: { writeText: () => Promise.reject(new Error('Denied')) }, configurable: true })
  })
  await page.goto('/')
  await expect(page.getByText('Fonts couldn’t load. Showing system fallbacks.')).toBeVisible()
  await page.getByRole('button', { name: 'Copy CSS', exact: true }).click()
  await expect(page.getByRole('textbox')).toBeFocused()
  await expect(page.getByRole('textbox')).toContainText('@import')
  await expect(page.getByText('CSS copied to clipboard')).toHaveCount(0)
  await page.unroute('https://fonts.googleapis.com/**')
  await page.getByRole('button', { name: 'Retry fonts' }).click()
  await expect(page.locator('.font-load-status')).toContainText('preview ready', { timeout: 20000 })
})

test('category search is lazy, and supported styles match the preview and export', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const fontRequests: string[] = []
  page.on('request', request => { if (request.url().startsWith('https://fonts.googleapis.com/css2')) fontRequests.push(request.url()) })
  await page.goto('/')
  await expect(page.locator('.catalog-status')).toContainText(`Search ${catalog.fonts.length.toLocaleString('en-US')}`)
  await expect(page.locator('.font-load-status')).toContainText('preview ready', { timeout: 20000 })
  const initialRequests = fontRequests.length
  await page.getByRole('button', { name: /Heading font:/ }).click()
  await page.getByRole('combobox', { name: 'Category', exact: true }).selectOption('handwriting')
  await page.getByRole('combobox', { name: 'Search heading fonts' }).fill('caveat')
  await expect(page.getByRole('listbox').getByRole('option')).toHaveCount(2)
  expect(fontRequests.length).toBe(initialRequests)
  await page.getByRole('combobox', { name: 'Search heading fonts' }).press('Enter')
  await page.getByRole('combobox', { name: 'Heading weight' }).selectOption('700')
  await expect(page.getByRole('combobox', { name: 'Heading style' }).getByRole('option')).toHaveCount(1)
  await expect(page.locator('.specimen-title')).toHaveCSS('font-weight', '700')
  await page.getByRole('button', { name: /Heading font:/ }).click()
  await page.getByRole('combobox', { name: 'Search heading fonts' }).fill('Playfair Display')
  await page.getByRole('combobox', { name: 'Search heading fonts' }).press('Enter')
  await page.getByRole('combobox', { name: 'Heading style' }).selectOption('italic')
  await page.getByRole('combobox', { name: 'Heading weight' }).selectOption('800')
  await page.getByRole('combobox', { name: 'Body style' }).selectOption('italic')
  await page.getByRole('combobox', { name: 'Body weight' }).selectOption('500')
  await expect(page.locator('.specimen-title')).toHaveCSS('font-style', 'italic')
  await expect(page.locator('.specimen-details h4').first()).toHaveCSS('font-weight', '800')
  await expect(page.locator('.website-specimen')).toHaveCSS('font-weight', '500')
  await expect(page.locator('.specimen-intro')).toHaveCSS('font-style', 'italic')
  await page.getByRole('button', { name: 'Copy CSS', exact: true }).click()
  const css = await page.evaluate(() => navigator.clipboard.readText())
  expect(css).toContain('Playfair+Display:ital,wght@1,800')
  expect(css).toContain('DM+Sans:ital,opsz,wght@1,9..40,500')
  expect(css).toContain('font-weight: 800; font-style: italic;')
  await page.getByRole('button', { name: /Heading font:/ }).click()
  await page.getByRole('combobox', { name: 'Search heading fonts' }).fill('Bebas Neue')
  await page.getByRole('combobox', { name: 'Search heading fonts' }).press('Enter')
  await expect(page.getByRole('combobox', { name: 'Heading weight' })).toHaveValue('400')
  await expect(page.getByRole('combobox', { name: 'Heading style' })).toHaveValue('normal')
})

