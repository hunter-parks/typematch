test('catalog outage keeps starter pairing usable and retry restores the complete library', async ({ page }) => {
  await page.route('**/fonts-catalog.json', route => route.fulfill({ status: 503, json: {} }))
  await page.route('**/api/fonts', route => route.fulfill({ status: 503, json: {} }))
  await page.goto('/')
  await expect(page.locator('.catalog-status')).toContainText('Full catalog unavailable')
  await expect(page.getByRole('radio')).toHaveCount(3)
  await expect(page.getByRole('button', { name: 'Copy CSS', exact: true })).toBeEnabled()
  await page.route('**/fonts-catalog.json', route => route.fulfill({ json: catalog }))
  await page.route('**/api/fonts', route => route.fulfill({ json: catalog }))
  await page.getByRole('button', { name: 'Retry catalog' }).click()
  await expect(page.locator('.catalog-status')).toContainText(`Search ${catalog.fonts.length.toLocaleString('en-US')}`)
})
