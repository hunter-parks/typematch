import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { catalog } from '../src/test/catalogFixture'

test.beforeEach(async ({ page }) => {
  // Keep interaction tests deterministic; font-service.spec.ts verifies the real provider.
  await page.route('**/fonts-catalog.json', route => route.fulfill({ json: catalog }))
  await page.route('**/api/fonts', route => route.fulfill({ json: catalog }))
})

test('search, recommendations, keyboard controls, preview modes and clipboard', async ({ page, context }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await expect(page.locator('.catalog-status')).toContainText(`Search ${catalog.fonts.length.toLocaleString('en-US')}`)
  await expect(page.getByRole('heading', { name: 'Better type. Together.' })).toBeVisible()
  await expect(page.getByRole('radio')).toHaveCount(3)
  await page.getByRole('radio', { name: 'DM Sans', exact: true }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('radio', { name: 'Source Sans 3', exact: true })).toBeChecked()
  await expect(page.locator('.website-specimen')).toHaveCSS('font-family', /Source Sans 3/)
  await page.getByRole('button', { name: 'Heading font: Playfair Display' }).click()
  await page.getByRole('combobox', { name: 'Search heading fonts' }).fill('Montserrat')
  await page.getByRole('combobox', { name: 'Search heading fonts' }).press('Enter')
  await expect(page.getByRole('button', { name: 'Heading font: Montserrat' })).toBeFocused()
  await expect(page.getByRole('radio', { name: 'Source Sans 3', exact: true })).toBeChecked()
  await page.getByRole('radio', { name: 'Source Serif 4', exact: true }).focus()
  await page.keyboard.press('Space')
  await expect(page.locator('.specimen-title')).toHaveCSS('font-family', /Montserrat/)
  await page.getByRole('button', { name: 'Mobile preview', exact: true }).click()
  await expect(page.getByTestId('specimen')).toHaveAttribute('data-mode', 'mobile')
  expect((await page.getByTestId('specimen').boundingBox())?.width).toBe(322)
  await page.getByRole('button', { name: 'Desktop preview', exact: true }).click()
  await expect(page.getByTestId('specimen')).toHaveAttribute('data-mode', 'desktop')
  await page.getByRole('button', { name: 'Copy CSS', exact: true }).click()
  const css = await page.evaluate(() => navigator.clipboard.readText())
  expect(css).toContain('Montserrat:wght@600')
  expect(css).toContain("font-family: 'Source Serif 4', serif")
  expect(css.startsWith('@import')).toBe(true)
  await page.getByRole('button', { name: 'Google Fonts import' }).click()
  await page.getByRole('button', { name: 'Copy import', exact: true }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toMatch(/^@import url\('https:\/\/fonts.googleapis.com\/css2\?.*'\);$/)
  expect(errors).toEqual([])
})

